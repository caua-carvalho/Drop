export const PRODUCTS: Product[] = SEEDS.map((seed, index) => {
  const slug = seed.name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
  return {
    ...seed,
    id: `dp-${String(index + 1).padStart(2, '0')}`,
    slug,
    images: gallery(seed.image, index + 1),
  };
});

export const COLORS: ProductColor[] = Object.values(CO).filter((c) => c.name !== 'Camo');

export const SIZES = [...new Set([...APPAREL, ...ONE, ...SHOES, ...PANTS])];

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function categoryLabel(id: CategoryId): string {
  return CATEGORIES.find((c) => c.id === id)?.label ?? id;
}

export function productsByCategory(id: CategoryId, limit?: number): Product[] {
  const list = PRODUCTS.filter((p) => p.category === id);
  return limit ? list.slice(0, limit) : list;
}

export function priceRange(): [number, number] {
  const prices = PRODUCTS.map((p) => p.price);
  return [Math.floor(Math.min(...prices)), Math.ceil(Math.max(...prices))];
}
