export function brandSlug(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export function brandNameBySlug(slug: string): string | undefined {
  return BRANDS.find((b) => b.slug === slug)?.name ?? PRODUCTS.find((p) => brandSlug(p.brand) === slug)?.brand;
}

